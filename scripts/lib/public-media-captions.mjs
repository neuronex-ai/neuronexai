function humanizeSlug(slug) {
  return slug
    .split("-")
    .map((word) => wordLabels.get(word) ?? word)
    .join(" ");
}

function sentenceCase(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

/**
 * Produces the short, user-facing process label shown above public screenshots.
 * The detailed manifest description remains available independently as alt text.
 */
export function createPublicMediaCaption(fileName) {
  const semanticParts = path.basename(fileName, path.extname(fileName)).split("--");
  const [, rawArea, rawProcess] = semanticParts;

  if (!rawArea || !rawProcess) {
    throw new Error(`Nome de captura sem area e processo: ${fileName}`);
  }

  const area = areaLabels.get(rawArea) ?? sentenceCase(humanizeSlug(rawArea));
  const process = processLabels.get(rawProcess) ?? humanizeSlug(rawProcess);

  return `${area}: ${process}`;
}
